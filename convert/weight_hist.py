"""Histograms of SmolLM2-135M's real weights before and after the Hadamard rotation, for the article's step 3 figure.

Each row of a weight matrix is cut into groups of G, every group is divided by its length (times sqrt(G), so a typical
weight has size 1, i.e. 1 sigma), and the values are counted in 0.25-wide bins from -6 to +6 sigma (values beyond are
counted in the edge bins). "After" is the same groups multiplied by the normalized Hadamard matrix from cq.py.
Writes docs/assets/weight-hist.js. Run: uv run --no-project --with numpy python convert/weight_hist.py
"""

import glob
import json
import os
import struct
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(__file__))
from cq import hadamard  # noqa: E402

PATH = glob.glob(os.path.expanduser("~/.cache/huggingface/hub/models--HuggingFaceTB--SmolLM2-135M-Instruct/snapshots/*/model.safetensors"))[0]
GROUPS, XM, BW = (8, 16, 32, 64), 6.0, 0.25
NB = int(2 * XM / BW)


def load(path):
    with open(path, "rb") as f:
        n = struct.unpack("<Q", f.read(8))[0]
        head = json.loads(f.read(n))
        base = 8 + n
        for k, v in head.items():
            if k == "__metadata__" or len(v["shape"]) != 2:
                continue
            a, b = v["data_offsets"]
            f.seek(base + a)
            raw = np.frombuffer(f.read(b - a), dtype=np.uint16)
            yield k, (raw.astype(np.uint32) << 16).view(np.float32).reshape(v["shape"])   # bf16 -> float32


def klass(name):
    if "embed_tokens" in name:
        return "embedding"
    if "self_attn" in name:
        return "attention"
    if "mlp" in name:
        return "mlp"
    return None


def hist(x):
    return np.bincount(np.clip(np.floor((x + XM) / BW).astype(int), 0, NB - 1), minlength=NB)


acc = {}
for name, W in load(PATH):
    c = klass(name)
    if not c:
        continue
    for g in GROUPS:
        if W.shape[1] % g:
            continue
        U = W.astype(np.float64).reshape(-1, g)
        ln = np.sqrt((U * U).mean(1, keepdims=True))
        ok = ln[:, 0] > 0
        U = U[ok] / ln[ok]
        R = U @ hadamard(g).astype(np.float64).T
        for key in (c, "all"):
            d = acc.setdefault((key, g), {"b": np.zeros(NB, np.int64), "a": np.zeros(NB, np.int64), "n": 0, "sb": [0, 0, 0, 0], "sa": [0, 0, 0, 0], "mb": 0, "ma": 0})
            d["b"] += hist(U.ravel()); d["a"] += hist(R.ravel()); d["n"] += U.size
            for s, X in (("sb", U), ("sa", R)):
                d[s][0] += (X ** 4).sum(); d[s][1] += (np.abs(X) > 3).sum()
            d["mb"] = max(d["mb"], np.abs(U).max()); d["ma"] = max(d["ma"], np.abs(R).max())

out = {"model": "SmolLM2-135M-Instruct", "bins": {"lo": -XM, "width": BW, "n": NB}, "data": {}}
for (key, g), d in sorted(acc.items()):
    n = d["n"]
    out["data"][f"{key}/{g}"] = {
        "n": int(n), "before": d["b"].tolist(), "after": d["a"].tolist(),
        "kurt": [round(d["sb"][0] / n, 2), round(d["sa"][0] / n, 2)],          # fourth moment; a Gaussian has 3
        "beyond3": [round(d["sb"][1] / n * 100, 3), round(d["sa"][1] / n * 100, 3)],   # % of weights beyond 3 sigma
        "max": [round(float(d["mb"]), 1), round(float(d["ma"]), 1)],
    }
    print(key, g, n, out["data"][f"{key}/{g}"]["kurt"], out["data"][f"{key}/{g}"]["beyond3"], out["data"][f"{key}/{g}"]["max"])
dst = os.path.join(os.path.dirname(__file__), "..", "docs", "assets", "weight-hist.js")
with open(dst, "w") as f:
    f.write("// Generated by convert/weight_hist.py: histograms of SmolLM2-135M's weights before and after rotation\nwindow.WEIGHT_HIST = " + json.dumps(out, separators=(",", ":")) + ";\n")
